<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use App\Models\Student;

class AuthController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | Страница авторизации
    |--------------------------------------------------------------------------
    */

    public function showLogin()
    {
        return view("auth");
    }

    /*
    |--------------------------------------------------------------------------
    | Профиль студента
    |--------------------------------------------------------------------------
    */

    public function studentProfile()
    {
        $user = Auth::user();

        $student = Student::with(["university", "direction"])
            ->where("email", $user->email)
            ->first();

        if (!$student) {
            abort(404, "Студент не найден");
        }

        return view("student-profile", compact("student", "user"));
    }

    /*
    |--------------------------------------------------------------------------
    | Универсальная авторизация
    |--------------------------------------------------------------------------
    */

    public function studentLogin(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | Валидация
        |--------------------------------------------------------------------------
        */

        $request->validate(
            [
                "email" => ["required", "email", "max:255"],
                "password" => ["required", "string", "min:6"],
            ],
            [
                "email.required" => "Email обязателен для заполнения.",
                "email.email" => "Введите корректный email адрес.",
                "email.max" => "Email слишком длинный.",
                "password.required" => "Пароль обязателен для заполнения.",
                "password.min" =>
                    "Пароль должен содержать не менее 6 символов.",
            ],
        );

        /*
        |--------------------------------------------------------------------------
        | Данные авторизации
        |--------------------------------------------------------------------------
        */

        $credentials = $request->only("email", "password");

        $remember = $request->boolean("remember");

        /*
        |--------------------------------------------------------------------------
        | Проверка логина
        |--------------------------------------------------------------------------
        */

        if (!Auth::attempt($credentials, $remember)) {
            return back()
                ->withInput($request->only("email"))
                ->withErrors([
                    "email" => "Неверный email или пароль.",
                ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Пользователь найден
        |--------------------------------------------------------------------------
        */

        /** @var \App\Models\User $user */
        $user = Auth::user();

        /*
        |--------------------------------------------------------------------------
        | Обновляем сессию
        |--------------------------------------------------------------------------
        */

        $request->session()->regenerate();

        /*
        |--------------------------------------------------------------------------
        | Проверка роли
        |--------------------------------------------------------------------------
        */

        if (!$user->role) {
            Auth::logout();

            return back()->withErrors([
                "email" => "У пользователя отсутствует роль.",
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | АДМИНИСТРАТОР
        |--------------------------------------------------------------------------
        */

        if ($user->role->name === "Администратор") {
            return redirect()->route("admin");
        }

        /*
        |--------------------------------------------------------------------------
        | СТУДЕНТ
        |--------------------------------------------------------------------------
        */

        if ($user->role->name === "Студент") {
            return redirect()->route("student-profile");
        }

        /*
        |--------------------------------------------------------------------------
        | КОМПАНИЯ
        |--------------------------------------------------------------------------
        */

        if ($user->role->name === "Компания") {
            return redirect()->route("company-profile");
        }

        /*
        |--------------------------------------------------------------------------
        | УНИВЕРСИТЕТ
        |--------------------------------------------------------------------------
        */

        if ($user->role->name === "Университет") {
            return redirect()->route("university-profile");
        }

        /*
        |--------------------------------------------------------------------------
        | Неизвестная роль
        |--------------------------------------------------------------------------
        */

        Auth::logout();

        return back()->withErrors([
            "email" => "Неизвестная роль пользователя.",
        ]);
    }

    /*
    |--------------------------------------------------------------------------
    | Logout
    |--------------------------------------------------------------------------
    */

    public function logout(Request $request)
    {
        Auth::logout();

        $request->session()->invalidate();

        $request->session()->regenerateToken();

        return redirect()->route("auth");
    }
}
